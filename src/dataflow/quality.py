"""Step 4 - StarCoder2 heuristic quality filters (The Stack v3 official rules).

From the Stack v3 dataset card, applied to the train subset:

    * Drop files with <25% alphabetic characters (alphanumeric for Assembly).
    * Drop files with average line length >100 or maximum line length >1000
      (exempting data/markup formats: Text, JSON, XML, HTML, Markdown, Roff, TeX).
    * Drop files with >100,000 lines and cap several data/config formats
      (JSON, YAML, ...) at 512 lines.
    * Drop files with giant base64/hex/unicode-escape data blobs, LFS pointers,
      and files with auto-generation markers in the first 5 lines.
    * For HTML, keep only files whose visible text is >=100 chars and >=20%
      of the content.
    * Drop a curated blocklist of non-code languages/extensions.
    * Cap the largest markup/config languages (XML, HTML, JSON, JavaScript) at
      a fixed byte budget; probabilistically downsample repos > 1.5 GB.

Every rule below maps 1:1 to that list; thresholds come from configs/.
"""

from __future__ import annotations

import re

from .models import FileRecord, StageStats

_LFS_POINTER = re.compile(rb"^version https://git-lfs\.github\.com/spec/v1", re.M)
_BASE64_BLOB = re.compile(r"[A-Za-z0-9+/]{4096,}")
_HEX_BLOB = re.compile(r"[0-9a-fA-F]{4096,}")
_UNICODE_ESCAPE_BLOB = re.compile(r"(?:\\u[0-9a-fA-F]{4}|\\x[0-9a-fA-F]{2}){2048,}")

# Auto-generation markers searched in the first N lines (Stack v3: 5).
_AUTOGEN_MARKERS = (
    "auto-generated", "autogenerated", "code generated",
    "generated by", "do not edit", "don't edit", "generated file",
    "@generated", "this file was generated",
)

# Non-code extensions to drop entirely (curated blocklist, grow as needed).
_BLOCKLIST_EXTS = {
    ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".ico", ".webp", ".tiff",
    ".pdf", ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx",
    ".zip", ".tar", ".gz", ".bz2", ".xz", ".7z", ".rar",
    ".woff", ".woff2", ".ttf", ".otf", ".eot",
    ".mp3", ".mp4", ".avi", ".mov", ".flac", ".wav", ".ogg",
    ".so", ".dll", ".dylib", ".exe", ".bin", ".o", ".a", ".class", ".jar",
    ".pyc", ".pyo", ".wasm", ".pack", ".idx", ".pdb", ".mo", ".po.cache",
    ".dump", ".core", ".iso", ".img", ".dmg",
}

_ALNUM = re.compile(r"[A-Za-z0-9]")
_ALPHA = re.compile(r"[A-Za-z]")

# HTML tags stripped when computing visible text ratio.
_HTML_TAG = re.compile(r"<[^>]*>")
_HTML_COMMENT = re.compile(r"<!--.*?-->", re.S)
_HTML_SCRIPT_STYLE = re.compile(r"<(script|style)\b[^>]*>.*?</\1>", re.S | re.I)


def alpha_ratio(text: str, language: str) -> float:
    """Alphabetic ratio; Assembly counts alphanumerics (StarCoder2 rule)."""
    if not text:
        return 0.0
    target = _ALNUM if language == "Assembly" else _ALPHA
    n = len(target.findall(text))
    return n / max(1, len(text))


def visible_text_of_html(text: str) -> str:
    t = _HTML_SCRIPT_STYLE.sub(" ", text)
    t = _HTML_COMMENT.sub(" ", t)
    t = _HTML_TAG.sub(" ", t)
    return re.sub(r"\s+", " ", t).strip()


class QualityFilter:
    def __init__(self, cfg: dict):
        self.cfg = cfg

    def check(self, rec: FileRecord) -> str | None:
        """Return a drop reason string, or None if the file passes."""
        text = rec.content
        ext = ("." + rec.file_path.rsplit("/", 1)[-1].rsplit(".", 1)[-1].lower()
               if "." in rec.file_path.rsplit("/", 1)[-1] else "")

        # blocklist of non-code extensions
        if ext in _BLOCKLIST_EXTS:
            return "blocklisted_extension"

        # LFS pointers
        if self.cfg.get("drop_lfs_pointers", True) and text.startswith(
            "version https://git-lfs.github.com/spec/v1"
        ):
            return "lfs_pointer"

        # auto-generation markers in the first N lines
        n_mark = int(self.cfg.get("auto_generated_marker_lines", 5))
        head_lines = text.splitlines()[:n_mark]
        head_l = "\n".join(head_lines).lower()
        if any(m in head_l for m in _AUTOGEN_MARKERS):
            return "auto_generated"

        # line statistics
        lines = text.splitlines()
        n_lines = len(lines)
        if n_lines > int(self.cfg.get("max_lines", 100000)):
            return "too_many_lines"

        # data/config formats capped at 512 lines
        data_langs = set(self.cfg.get("data_format_languages", []))
        cap = int(self.cfg.get("data_format_line_cap", 512))
        if rec.language in data_langs and n_lines > cap:
            return "data_format_over_line_cap"

        # alphabetic ratio
        if alpha_ratio(text, rec.language) < float(
            self.cfg.get("min_alpha_ratio", 0.25)
        ):
            return "low_alpha_ratio"

        # line length, with per-format exemption
        exempt = set(self.cfg.get("line_len_exempt", []))
        if rec.language not in exempt and lines:
            max_ll = max(len(l) for l in lines)
            avg_ll = len(text) / max(1, n_lines)
            if max_ll > int(self.cfg.get("max_line_len", 1000)):
                return "max_line_length"
            if avg_ll > int(self.cfg.get("max_avg_line_len", 100)):
                return "avg_line_length"

        # giant encoded blobs
        if self.cfg.get("drop_base64_hex_blobs", True):
            if (_BASE64_BLOB.search(text) or _HEX_BLOB.search(text)
                    or _UNICODE_ESCAPE_BLOB.search(text)):
                return "encoded_blob"

        # HTML visible-text rule
        if rec.language == "HTML":
            vis = visible_text_of_html(text)
            min_chars = int(self.cfg.get("html_min_visible_chars", 100))
            min_ratio = float(self.cfg.get("html_min_visible_ratio", 0.20))
            if len(vis) < min_chars:
                return "html_low_visible_text"
            if len(vis) / max(1, len(text)) < min_ratio:
                return "html_low_visible_ratio"

        return None


def filter_files(records: list[FileRecord], cfg: dict) -> tuple[list[FileRecord], StageStats]:
    qf = QualityFilter(cfg)
    stats = StageStats(stage="quality")
    kept: list[FileRecord] = []
    for rec in records:
        stats.seen += 1
        reason = qf.check(rec)
        if reason is None:
            kept.append(rec)
            stats.kept += 1
        else:
            rec.drop_reason = reason
            stats.drop(reason)
    return kept, stats
