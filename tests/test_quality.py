import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from dataflow.models import FileRecord
from dataflow.quality import filter_files, alpha_ratio, visible_text_of_html
from dataflow.licenses import is_license_file, classify


def _rec(text, path="a.py", lang="Python"):
    return FileRecord(repo_path="o/r", file_path=path, size_bytes=len(text),
                      sha1="x", content=text, language=lang)


CFG = {
    "min_alpha_ratio": 0.25, "max_avg_line_len": 100, "max_line_len": 1000,
    "line_len_exempt": ["Text", "JSON", "XML", "HTML", "Markdown", "Roff", "TeX"],
    "max_lines": 100000, "data_format_line_cap": 512,
    "data_format_languages": ["JSON", "YAML", "TOML", "CSV", "XML", "INI", "Properties"],
    "drop_base64_hex_blobs": True, "drop_lfs_pointers": True,
    "auto_generated_marker_lines": 5,
    "html_min_visible_chars": 100, "html_min_visible_ratio": 0.20,
}


def test_normal_python_passes():
    kept, st = filter_files([_rec("def hello():\n    return 'world'\n" * 3)], CFG)
    assert len(kept) == 1 and st.dropped == 0


def test_low_alpha_ratio_dropped():
    kept, st = filter_files([_rec("11111111111111111111111111111111")], CFG)
    assert len(kept) == 0
    assert st.reasons.get("low_alpha_ratio") == 1


def test_long_line_dropped():
    kept, st = filter_files([_rec("x = 1  # " + "a" * 2000)], CFG)
    assert st.reasons.get("max_line_length") == 1


def test_json_exempt_from_line_length_but_capped():
    long_json = "{\n" + ",\n".join(f'"k{i}": "v"' for i in range(600)) + "\n}"
    kept, st = filter_files([_rec(long_json, path="d.json", lang="JSON")], CFG)
    assert st.reasons.get("data_format_over_line_cap") == 1


def test_autogenerated_marker_dropped():
    kept, st = filter_files([_rec("# Code generated by tool. DO NOT EDIT.\nprint(1)\n")], CFG)
    assert st.reasons.get("auto_generated") == 1


def test_lfs_pointer_dropped():
    lfs = "version https://git-lfs.github.com/spec/v1\noid sha256:abc\nsize 123\n"
    _, st = filter_files([_rec(lfs)], CFG)
    assert st.reasons.get("lfs_pointer") == 1


def test_blocklisted_extension():
    _, st = filter_files([_rec("binaryish", path="img.png")], CFG)
    assert st.reasons.get("blocklisted_extension") == 1


def test_html_visible_text():
    html = "<html><body>" + "<p>Some meaningful visible text here. </p>" * 10 + "</body></html>"
    vis = visible_text_of_html(html)
    assert len(vis) >= 100
    html_bad = "<html><body><script>" + "code();" * 200 + "</script></body></html>"
    _, st = filter_files([_rec(html_bad, path="i.html", lang="HTML")], CFG)
    assert st.reasons.get("html_low_visible_text") == 1


def test_base64_blob():
    # Text is line-length-exempt (like real-world blob files), so the blob rule fires
    blob = "Abc123+/" * 700
    _, st = filter_files([_rec(blob, path="payload.txt", lang="Text")], CFG)
    assert st.reasons.get("encoded_blob") == 1


def test_license_helpers():
    assert is_license_file("LICENSE")
    assert is_license_file("LICENSE.md")
    assert is_license_file("src/lib/MIT.txt")
    assert not is_license_file("src/main.py")
    assert classify(["MIT"]) == "permissive"
    assert classify(["GPL-3.0-only"]) == "non_permissive"
    assert classify([]) == "no_license"


def test_alpha_ratio_assembly_alnum():
    assert alpha_ratio("abc123XYZ", "Assembly") > 0.9
